package cluster

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"
	"time"

	"github.com/redis/go-redis/v9"
)

const (
	invalidLineageTTL       = time.Hour
	invalidLineageCapacity  = 10_000
	invalidLineageMaxValues = 100_000
)

// InvalidLineage shares rejected continuation state across replicas. The
// cluster-wide bounds and all session keys share one slot so admission,
// expiration and renewal are atomic. Only digests and item IDs are stored.
type InvalidLineage struct{ client *Client }

func NewInvalidLineage(client *Client) *InvalidLineage { return &InvalidLineage{client: client} }

// The session index stores full Redis keys generated by this store. Eviction
// only touches these same-slot keys; it never scans the Redis keyspace.
var invalidLineageScript = redis.NewScript(`
local sessions, counts, current = KEYS[1], KEYS[2], KEYS[3]
local clock = redis.call('TIME')
local now = tonumber(clock[1]) * 1000 + math.floor(tonumber(clock[2]) / 1000)
local ttl = tonumber(ARGV[2])
local function remove(key)
  local count = tonumber(redis.call('HGET', counts, key) or '0')
  redis.call('HINCRBY', counts, '!total', -count)
  redis.call('HDEL', counts, key)
  redis.call('ZREM', sessions, key)
  redis.call('DEL', key)
end
for _, key in ipairs(redis.call('ZRANGEBYSCORE', sessions, '-inf', now)) do remove(key) end
local exists = redis.call('ZSCORE', sessions, current)
if ARGV[1] == 'lookup' and not exists then return {} end
if not exists and redis.call('ZCARD', sessions) >= tonumber(ARGV[3]) then
  local oldest = redis.call('ZRANGE', sessions, 0, 0)
  remove(oldest[1])
end
local added = 0
if ARGV[1] == 'mark' then
  local total = tonumber(redis.call('HGET', counts, '!total') or '0')
  for index = 5, #ARGV do
    if total >= tonumber(ARGV[4]) then break end
    local fresh = redis.call('HSETNX', current, ARGV[index], '1')
    added = added + fresh
    total = total + fresh
  end
  redis.call('HINCRBY', counts, current, added)
  redis.call('HINCRBY', counts, '!total', added)
end
redis.call('ZADD', sessions, now + ttl, current)
redis.call('PEXPIRE', current, ttl)
redis.call('PEXPIRE', sessions, ttl)
redis.call('PEXPIRE', counts, ttl)
if ARGV[1] == 'lookup' then return redis.call('HKEYS', current) end
return added
`)

func (store *InvalidLineage) keys(key string) []string {
	sum := sha256.Sum256([]byte(key))
	return []string{
		store.client.Key("lineage", "{lineage}", "sessions"),
		store.client.Key("lineage", "{lineage}", "counts"),
		store.client.Key("lineage", "{lineage}", hex.EncodeToString(sum[:])),
	}
}

func (store *InvalidLineage) Lookup(ctx context.Context, key string) (map[string]struct{}, map[string]struct{}, error) {
	if key == "" {
		return nil, nil, nil
	}
	callCtx, cancel := context.WithTimeout(ctx, stateTimeout)
	defer cancel()
	values, err := invalidLineageScript.Run(callCtx, store.client.UniversalClient, store.keys(key), "lookup", invalidLineageTTL.Milliseconds(), invalidLineageCapacity, invalidLineageMaxValues).StringSlice()
	if err != nil {
		return nil, nil, fmt.Errorf("look up rejected continuation state: %w", err)
	}
	digests, ids := make(map[string]struct{}), make(map[string]struct{})
	for _, value := range values {
		if strings.HasPrefix(value, "d:") {
			digests[value[2:]] = struct{}{}
		}
		if strings.HasPrefix(value, "i:") {
			ids[value[2:]] = struct{}{}
		}
	}
	return digests, ids, nil
}

func (store *InvalidLineage) Mark(ctx context.Context, key string, digests, ids []string) (int, error) {
	if key == "" || len(digests)+len(ids) == 0 {
		return 0, nil
	}
	args := []any{"mark", invalidLineageTTL.Milliseconds(), invalidLineageCapacity, invalidLineageMaxValues}
	for _, group := range []struct {
		prefix string
		values []string
	}{{"d:", digests}, {"i:", ids}} {
		for _, value := range group.values {
			if len(args)-4 >= invalidLineageMaxValues {
				break
			}
			if value = strings.TrimSpace(value); value != "" {
				args = append(args, group.prefix+value)
			}
		}
	}
	if len(args) == 4 {
		return 0, nil
	}
	callCtx, cancel := context.WithTimeout(ctx, stateTimeout)
	defer cancel()
	added, err := invalidLineageScript.Run(callCtx, store.client.UniversalClient, store.keys(key), args...).Int()
	if err != nil {
		return 0, fmt.Errorf("remember rejected continuation state: %w", err)
	}
	return added, nil
}
